const COIN = ["..GGGG..", ".GGYYGG.", "GGYGGGGG", "GGYGGGGG", "GGYGGGGG", "GGYGGGGG", ".GGGGGG.", "..GGGG.."];

function drawMap(ctx: CanvasRenderingContext2D, map: string[], x: number, y: number, u: number, pal: Record<string, string>): void {
  for (let r = 0; r < map.length; r++) {
    for (let c = 0; c < map[r].length; c++) {
      const col = pal[map[r][c]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(Math.round(x + c * u), Math.round(y + r * u), u, u);
    }
  }
}

export const DARIO_W = 12;
export const DARIO_H = 16;

export function drawDario(ctx: CanvasRenderingContext2D, x: number, y: number, u: number): void {
  drawMap(ctx, DARIO, x, y, u, PALETTE);
}

export function drawCoin(ctx: CanvasRenderingContext2D, x: number, y: number, u: number): void {
  drawMap(ctx, COIN, x, y, u, { G: "#ffd23f", Y: "#fff3b0" });
}
