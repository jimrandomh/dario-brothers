/** Glyph advance in font pixels (5 wide + 1 gap). */
export const ADV = 6;
export const GLYPH_H = 7;

export interface PixelTextOpts {
  color?: string;
  shadow?: string;
  align?: "left" | "center" | "right";
}

export function textWidth(text: string, u: number): number {
  return Math.max(0, text.length * ADV - 1) * u;
}

/** Draw text with `u` screen pixels per font pixel. */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  u: number,
  opts: PixelTextOpts = {},
): void {
  const s = text.toUpperCase();
  const w = textWidth(s, u);
  let x0 = opts.align === "center" ? x - w / 2 : opts.align === "right" ? x - w : x;
  x0 = Math.round(x0);
  y = Math.round(y);
  const pass = (color: string, dx: number, dy: number) => {
    ctx.fillStyle = color;
    for (let i = 0; i < s.length; i++) {
      const g = GLYPHS[s[i]] ?? GLYPHS["?"];
      const gx = x0 + i * ADV * u + dx;
      for (let r = 0; r < GLYPH_H; r++) {
        const row = g[r];
        for (let c = 0; c < 5; c++) if (row[c] === "#") ctx.fillRect(gx + c * u, y + r * u + dy, u, u);
      }
    }
  };
  if (opts.shadow) pass(opts.shadow, u, u);
  pass(opts.color ?? "#fff", 0, 0);
}

