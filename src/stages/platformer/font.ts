export const GLYPH_W = 5;
export const GLYPH_H = 7;
const ADVANCE = 6;

const cache = new Map<string, HTMLCanvasElement>();

function glyphCanvas(ch: string, color: string): HTMLCanvasElement | null {
  const key = color + "|" + ch;
  let c = cache.get(key);
  if (c) return c;
  const rows = (GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()])?.split("|");
  if (!rows) return null;
  c = document.createElement("canvas");
  c.width = GLYPH_W;
  c.height = GLYPH_H;
  const g = c.getContext("2d")!;
  g.fillStyle = color;
  rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === "#") g.fillRect(x, y, 1, 1);
  });
  cache.set(key, c);
  return c;
}

export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * scale;
}

export interface TextOpts {
  color?: string;
  scale?: number;
  /** Drop-shadow color (1px down-right, scaled). */
  shadow?: string;
  align?: "left" | "center" | "right";
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, o: TextOpts = {}): void {
  const scale = o.scale ?? 1;
  const w = textWidth(text, scale);
  let sx = x;
  if (o.align === "center") sx = x - Math.floor(w / 2);
  else if (o.align === "right") sx = x - w;
  sx = Math.round(sx);
  const sy = Math.round(y);
  if (o.shadow) drawRun(ctx, text, sx + scale, sy + scale, o.shadow, scale);
  drawRun(ctx, text, sx, sy, o.color ?? "#fff", scale);
}

function drawRun(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale: number) {
  for (let i = 0; i < text.length; i++) {
    const g = glyphCanvas(text[i], color);
    if (g) ctx.drawImage(g, x + i * ADVANCE * scale, y, GLYPH_W * scale, GLYPH_H * scale);
  }
}
